"""Write routine.js: the task table and settings, as data for the README pictures.

    python docs/images/src/export_routine.py

Run it after changing pcr_routine/routine.py or config.py, then render the pictures again
(see the comment at the top of each HTML file). tests/test_docs.py fails while routine.js
is out of date.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import cv2
import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2]))

from pcr_routine.bot import Click, Pause, Step, Switch  # noqa: E402
from pcr_routine.config import Settings  # noqa: E402
from pcr_routine.routine import DAILY_ROUTINE, TASKS  # noqa: E402

OUTPUT = HERE / "routine.js"


def read(path: Path) -> np.ndarray:
    return cv2.imdecode(np.fromfile(path, dtype=np.uint8), cv2.IMREAD_UNCHANGED)


def visible_box(path: Path) -> list[int]:
    """The part of a button image worth showing: its biggest opaque area, as [x, y, w, h].

    Some images have a large transparent margin (and a stray dot) around the button.
    """
    image = read(path)
    height, width = image.shape[:2]
    if image.ndim < 3 or image.shape[2] < 4:
        return [0, 0, width, height]
    count, _, stats, _ = cv2.connectedComponentsWithStats((image[:, :, 3] > 0).astype(np.uint8))
    if count < 2:
        return [0, 0, width, height]
    biggest = 1 + int(np.argmax(stats[1:, cv2.CC_STAT_AREA]))
    x, y, w, h = (int(v) for v in stats[biggest, :4])
    return [x, y, w, h]


def image_info(settings: Settings, name: str) -> dict:
    path = settings.image_dir / name
    height, width = read(path).shape[:2]
    return {"file": name, "size": [width, height], "box": visible_box(path)}


def step_info(settings: Settings, step: Step) -> dict:
    if isinstance(step, Click):
        return {
            "kind": "click",
            "image": image_info(settings, step.image),
            "label": step.label,
            "timeout": settings.wait_timeout if step.timeout is None else step.timeout,
            "pause_before": step.pause_before,
            "pause_after": step.pause_after,
            "optional": step.optional,
        }
    if isinstance(step, Switch):
        return {
            "kind": "switch",
            "before": image_info(settings, step.before),
            "after": image_info(settings, step.after),
            "label": step.label,
        }
    if isinstance(step, Pause):
        return {"kind": "pause", "seconds": step.seconds, "reason": step.reason}
    raise TypeError(f"unknown step {step!r}")


def build(settings: Settings | None = None) -> dict:
    settings = settings or Settings()
    return {
        "settings": {
            "match_threshold": settings.match_threshold,
            "wait_timeout": settings.wait_timeout,
            "switch_before_timeout": settings.switch_before_timeout,
            "switch_after_timeout": settings.switch_after_timeout,
        },
        "daily": list(DAILY_ROUTINE),
        "tasks": [
            {"name": task.name, "title": task.title, "steps": [step_info(settings, s) for s in task.steps]}
            for task in TASKS.values()
        ],
    }


def render(data: dict) -> str:
    body = json.dumps(data, ensure_ascii=False, indent=1)
    # Keep number lists such as image boxes on one line.
    body = re.sub(r"\[\s*([-\d.,\s]+?)\s*\]", lambda m: "[" + " ".join(m.group(1).split()) + "]", body)
    header = "// Generated by export_routine.py from pcr_routine/routine.py. Do not edit."
    return f"{header}\nwindow.ROUTINE = {body};\n"


if __name__ == "__main__":
    OUTPUT.write_text(render(build()), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
